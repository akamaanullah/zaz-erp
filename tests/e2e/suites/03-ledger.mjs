import { chooseFarm, loadState, openSession, runSuite, shot, submitAction, submitModal, toastText } from '../lib.mjs';

const state = await loadState();
const originOf = (page) => new URL(page.url()).origin;

await runSuite('03-ledger', async ({ check, browser, bucket }) => {
  const accountant = await openSession(browser, state.accountant.username, state.accountant.password, bucket);
  await check('expense keeps its rate after the category rate changes', async () => {
    const origin = originOf(accountant.page);
    await accountant.page.goto(origin + '/expenses', { waitUntil: 'domcontentloaded' });
    await accountant.page.click('#add');
    const category = await accountant.page.locator('[name=Category] option').evaluateAll((opts) => (opts.find((opt) => opt.textContent.includes('Tractor')) || {}).value || '');
    if (!category) throw new Error('tractor category missing from the expense form');
    await accountant.page.selectOption('[name=Category]', category);
    await accountant.page.selectOption('[name=Target]', 'seri');
    await accountant.page.fill('[name=Crop]', 'SnapCrop');
    await accountant.page.fill('[name=Qty]', '2');
    await accountant.page.fill('[name=Rate]', '10');
    await submitModal(accountant.page, 'Add expense');
    await toastText(accountant.page);
  });
  await check('Maund and kilogram sales use weight times the rate in that unit', async () => {
    const origin = originOf(accountant.page);
    await accountant.page.goto(origin + '/sales', { waitUntil: 'domcontentloaded' });
    await accountant.page.click('#add');
    await accountant.page.selectOption('[name=Target]', 'seri');
    await accountant.page.fill('[name=Crop]', 'MaundCrop');
    await accountant.page.selectOption('[name=Unit]', 'maund');
    await accountant.page.fill('[name=Weight]', '2');
    await accountant.page.fill('[name=Rate]', '100');
    const maund = await accountant.page.locator('#liveTot').innerText();
    if (!maund.includes('200')) throw new Error('maund preview ' + maund);
    await submitModal(accountant.page, 'Add sale');
    await toastText(accountant.page);
    await accountant.page.click('#add');
    await accountant.page.selectOption('[name=Target]', 'seri');
    await accountant.page.fill('[name=Crop]', 'KgCrop');
    await accountant.page.selectOption('[name=Unit]', 'kg');
    await accountant.page.fill('[name=Weight]', '10');
    await accountant.page.fill('[name=Rate]', '3');
    const kg = await accountant.page.locator('#liveTot').innerText();
    if (!kg.includes('30')) throw new Error('kg preview ' + kg);
    await submitModal(accountant.page, 'Add sale');
    await toastText(accountant.page);
    await accountant.page.reload({ waitUntil: 'domcontentloaded' });
    await accountant.page.fill('input[type=search]', 'KgCrop');
    await accountant.page.waitForTimeout(500);
    const text = await accountant.page.locator('#t').innerText();
    if (!text.includes('KgCrop') || !text.includes('30')) throw new Error(text.slice(0, 200));
  });
  await check('Hari advance is recorded and stays pending', async () => {
    const origin = originOf(accountant.page);
    await accountant.page.goto(origin + '/advances', { waitUntil: 'domcontentloaded' });
    await accountant.page.waitForSelector('#add:not([disabled])');
    await accountant.page.click('#add');
    const value = await accountant.page.locator('[name=Hari] option').first().getAttribute('value');
    await accountant.page.selectOption('[name=Hari]', value);
    await accountant.page.fill('[name=Reason]', 'Medical');
    await accountant.page.fill('[name=Amount]', '15');
    await submitAction(accountant.page, 'Record advance', '/api/advances/create');
    await accountant.page.reload({ waitUntil: 'domcontentloaded' });
    const pending = accountant.page.locator('#t tbody tr', { hasText: 'Medical' }).filter({ hasText: 'Pending' });
    await pending.first().waitFor({ timeout: 15000 });
    if (await pending.count() < 1) throw new Error('new advance is not pending');
  });
  await accountant.close();

  const owner = await openSession(browser, 'owner', state.password, bucket);
  await check('changing the category rate does not rewrite the saved expense', async () => {
    const origin = originOf(owner.page);
    await owner.page.goto(origin + '/rates', { waitUntil: 'domcontentloaded' });
    await owner.page.locator('tr', { hasText: 'Tractor' }).locator('[data-edit]').click();
    const before = await owner.page.locator('form.modal input[name=name]').inputValue();
    await owner.page.fill('form.modal input[name=rate]', '99');
    await owner.page.waitForTimeout(80);
    const after = await owner.page.locator('form.modal input[name=name]').inputValue();
    const rate = await owner.page.locator('form.modal input[name=rate]').inputValue();
    if (after !== before) throw new Error('typing the rate changed the category name to ' + after);
    if (Number(rate) !== 99) throw new Error('rate field is ' + rate);
    await submitModal(owner.page, 'Save changes');
    await toastText(owner.page);
    const saved = await owner.page.locator('#t tr', { hasText: before }).innerText();
    if (saved.includes('99' + before)) throw new Error('saved category name gained the rate: ' + saved.slice(0, 180));
    if (!saved.includes('99')) throw new Error('saved rate is not 99: ' + saved.slice(0, 180));
    await owner.page.goto(origin + '/expenses', { waitUntil: 'domcontentloaded' });
    await chooseFarm(owner.page, 'E2E North');
    await owner.page.waitForTimeout(400);
    await owner.page.fill('#t input[type=search]', 'SnapCrop');
    await owner.page.waitForTimeout(600);
    const text = await owner.page.locator('#t').innerText();
    if (!text.includes('10') || text.includes('198')) throw new Error(text.slice(0, 220));
  });
  await check('search and sort still leave single and bulk approval working', async () => {
    const origin = originOf(owner.page);
    await owner.page.goto(origin + '/approvals', { waitUntil: 'domcontentloaded' });
    await chooseFarm(owner.page, 'E2E North');
    await owner.page.waitForSelector('#t button[data-ok]', { timeout: 15000 });
    await owner.page.fill('#t input[type=search]', 'SnapCrop');
    await owner.page.waitForTimeout(500);
    await owner.page.locator('#t th.sortable').first().click();
    await owner.page.waitForTimeout(400);
    const button = owner.page.locator('#t button[data-ok]').first();
    if (await button.count() !== 1) throw new Error('approve button missing after search and sort');
    await button.click();
    await toastText(owner.page);
    await owner.page.reload({ waitUntil: 'domcontentloaded' });
    await chooseFarm(owner.page, 'E2E North');
    await owner.page.waitForTimeout(500);
    const before = await owner.page.locator('#t button[data-ok]').count();
    if (!before) throw new Error('no remaining pending row for bulk approval');
    await owner.page.click('#all');
    await submitModal(owner.page, 'Approve all');
    await toastText(owner.page);
    await owner.page.reload({ waitUntil: 'domcontentloaded' });
    await chooseFarm(owner.page, 'E2E North');
    await owner.page.waitForTimeout(500);
    if (await owner.page.locator('#t button[data-ok]').count()) throw new Error('pending rows remained after bulk approval');
    await shot(owner.page, 'e2e-bulk-approved.png');
  });
  await check('approved settlement print uses the approved statement', async () => {
    const origin = originOf(owner.page);
    await owner.page.goto(origin + '/settlements', { waitUntil: 'domcontentloaded' });
    await chooseFarm(owner.page, 'E2E North');
    await owner.page.waitForSelector('[data-print]', { timeout: 15000 });
    await owner.page.evaluate(() => { window.__printed = false; window.print = () => { window.__printed = true; }; });
    await owner.page.locator('[data-print]').first().click();
    await owner.page.locator('#printview').getByText('حتمي').waitFor({ state: 'attached', timeout: 10000 });
    const printed = await owner.page.evaluate(() => window.__printed === true);
    if (!printed) throw new Error('print handler did not run');
    await shot(owner.page, 'e2e-settlement.png');
  });
  await owner.close();
});
